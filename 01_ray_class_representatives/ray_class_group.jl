# ray_class_group.jl
#
# Top-level construction of explicit ray class group representatives,
# combining the Picard group of O, coprime representative search, and
# principal ray class enumeration.
#
#   - num_principal_ray_classes:       how many principal ray classes to
#                                       look for (index computation).
#   - ray_class_group_representatives: full set of explicit ray class group
#                                       representatives, as (Picard rep,
#                                       principal ray class rep) pairs.
#
# NOTE (pre-existing, not introduced by this reorganization): this file
# calls make_coprime_representatives(O, m, mP_O, group_elems) with 4
# arguments, but coprime_representatives.jl defines it with a required 5th
# argument `d` with no default. This call will error as written; flagging
# for the project owner rather than silently changing behavior.
#
# (Renamed from full_rayclassgrp.jl; one superseded draft of
# ray_class_group_representatives that was block-commented out in the
# original file has been removed - see the original upload if needed.)
#
# FIX (per project owner): num_principal_ray_classes previously computed
# N = N1*N3/(N2*N4) - 1, with N2 taken from ray_unit_quotient(OK, O, ...) -
# i.e. measured in terms of OK's own unit structure, with no correction for
# O's (possibly much smaller) unit subgroup. This is the SAME bug pattern
# already found and fixed in galois_twist_vector_lattice_search.jl (and its
# descendants galois_action_ghost_sics*.jl) much earlier in this project:
# the period of OK's fundamental unit isn't divided down to O's own
# fundamental unit's period (t0), and -eps^k is never checked separately
# from +eps^k (silently doubling N2, hence halving N, whenever the true
# minimal solution has the form -eps^k0 rather than +eps^k0). Replaced
# below with the direct-unit-search version already verified correct in
# galois_twist_vector_lattice_search.jl, which no longer needs
# residue_unit_quotient/ray_unit_quotient at all (unit_group_quotients.jl
# is still included below since ray_class_group_representatives itself
# doesn't need it either, but other code including this file may expect it
# available transitively).

using Hecke
include("unit_group_quotients.jl")
include("ray_class_enumeration.jl")
include("coprime_representatives.jl")

function num_principal_ray_classes(OK, O, m, Sigma)
    K = number_field(O)

    f = conductor(O)

    m_O = ideal(O, minimum(m))
    R_m, _ = quo(O, m_O)
    U_Rm, _ = unit_group(R_m)
    N1 = Int(order(U_Rm)) * 2^length(Sigma)

    U_O, mU_O = unit_group(O)
    R_m_O, proj_m_O = quo(O, m)
    minus_one = O(-1)
    torsion_index = (isone(proj_m_O(minus_one)) &&
                     all(sign(K(elem_in_nf(minus_one)), p) > 0
                         for p in Sigma)) ? 1 : 2

    # Robustly find a generator of infinite order (the fundamental unit),
    # rather than assuming it is always U_OK[2] -- Hecke does not guarantee
    # generator ordering.
    U_OK, mU_OK = unit_group(OK)
    eps = nothing
    for i in 1:ngens(U_OK)
        cand = elem_in_nf(mU_OK(U_OK[i]))
        is_torsion = try
            is_torsion_unit(OK(cand))[1]
        catch
            # Fallback: a torsion unit of a real quadratic field is a root
            # of unity, so it must be +-1 (norm 1, and equal to its own
            # inverse up to sign at every real embedding of absolute value 1).
            all(abs(sign(cand, p)) == 1 && cand == 1 || cand == -1 for p in real_places(K))
        end
        if !is_torsion
            eps = cand
            break
        end
    end
    eps === nothing && error("num_principal_ray_classes: could not find an infinite-order unit generator of OK")

    # Search for the minimal k such that EITHER eps^k or -eps^k is congruent
    # to 1 mod m and positive at every place in Sigma. Checking only the
    # pure power eps^k (and never -eps^k) is unsound: since -1 itself is
    # never in the kernel (Sigma is nonempty, so -1 always fails
    # positivity), a subgroup containing the minimal solution u0 cannot also
    # contain -u0. If the true minimal solution is u0 = -eps^{k0}, then the
    # smallest PURE power of eps back in the kernel is eps^{2 k0} = u0^2,
    # i.e. exactly double the true period -- silently corrupting N2 by a
    # factor of 2 whenever this case is hit.
    # First find t0: the minimal positive k such that eps^k is even
    # representable as an element of O. O's own unit group is generated by
    # eps_O := eps^t0 (together with -1), NOT by eps itself whenever
    # t0 > 1 -- O is a proper (non-maximal, conductor > 1) suborder of OK,
    # so most powers of OK's fundamental unit simply do not lie in O.
    t0 = 0
    eps_O_elem = nothing
    for k in 1:100_000
        cand = try O(OK(eps^k)) catch; nothing end
        if cand !== nothing
            t0 = k
            eps_O_elem = cand
            break
        end
    end
    t0 == 0 && error("num_principal_ray_classes: could not find any representable power of eps in O")

    # Now search over MULTIPLES of t0 (i.e. powers of O's own fundamental
    # unit eps_O = eps^t0) for the minimal j such that eps_O^j (or its
    # negative) is congruent to 1 mod m and positive at every place in
    # Sigma. Every representable power of eps is automatically a multiple
    # of t0, so this is equivalent to (and replaces) searching over all k.
    j0 = 0
    for j in 1:100_000
        k = j * t0
        epsk_nf = eps^k
        epsk_O = O(OK(epsk_nf))  # guaranteed representable since k is a multiple of t0

        pos_ok = isone(proj_m_O(epsk_O)) && all(sign(K(epsk_nf), p) > 0 for p in Sigma)
        neg_epsk_O = O(OK(-epsk_nf))
        neg_pos_ok = isone(proj_m_O(neg_epsk_O)) && all(sign(-K(epsk_nf), p) > 0 for p in Sigma)

        if pos_ok || neg_pos_ok
            j0 = j
            break
        end
    end
    j0 == 0 && error("Period not found")
    N2 = torsion_index * j0

    N1_div_N2, r = divrem(N1, N2)
    r != 0 && error("num_principal_ray_classes: N1 = $N1 is not divisible by N2 = $N2 (period/torsion computation is likely still wrong)")
    N = N1_div_N2 - 1
    return N
end

function ray_class_group_representatives(K, O, m, Sigma)
    OK = maximal_order(K)

    # Step 1: get Picard group representatives coprime to m
    P_O, mP_O = picard_group(O)
    gens_P = gens(P_O)
    divs = elementary_divisors(P_O)
    ranges = [0:Int(d)-1 for d in divs]

    group_elems = []
    for exps in Iterators.product(ranges...)
        g = isempty(gens_P) ? zero(P_O) : sum(exps[i] * gens_P[i] for i in 1:length(gens_P))
        push!(group_elems, g)
    end

    picard_reps = make_coprime_representatives(O, m, mP_O, group_elems)

    # Step 2: compute number of principal ray classes
    N = num_principal_ray_classes(OK, O, m, Sigma)
    println("Number of principal ray classes: ", N)

    # Step 3: enumerate principal ray classes
    principal_reps = enumerate_principal_ray_classes(K, O, m, Sigma, N)

    # Step 4: combine
    all_reps = []           # list of ideal products J * I
    all_triples = []        # list of tuples (J, I, gamma)

    trivial = ideal(O, 1)

    for J in picard_reps
        # trivial principal ray class: gamma = 1
        push!(all_reps, J)
        push!(all_triples, (J, trivial, one(K)))

        # nontrivial principal ray classes: gamma from enumeration
        for (I, gamma, h) in principal_reps
            push!(all_reps, J * I)
            push!(all_triples, (J, I, elem_in_nf(gamma)))
        end
    end

    return all_reps, all_triples
end
